"""「关于 / 功能说明」的正文。

界面(信息区、侧栏底部)以前写着一堆常驻提示文字, 现在全部收到这里,
只在菜单「帮助 → 关于 / 功能说明…」里看 —— 界面上只留真正在变的数值。
"""
from __future__ import annotations

from .global_hotkey import ACTION_LABELS, DEFAULT_BINDINGS, describe_binding

APP_TITLE = "跑图线路测试器"
APP_SUBTITLE = "记录“重生后多久到达某位置”的独立小工具"


def hotkey_lines() -> list[str]:
    """三行快捷键说明(顺序: 开始 / 标记 / 结束)。"""
    return [
        f"{ACTION_LABELS[a]} —— {describe_binding(DEFAULT_BINDINGS[a])}"
        for a in ("start", "mark", "stop")
    ]


def about_html() -> str:
    """功能说明正文(HTML, 给 QTextBrowser 用)。"""
    keys = "".join(f"<li>{line}</li>" for line in hotkey_lines())
    return f"""
<h2>{APP_TITLE}</h2>
<p style="color:#888">{APP_SUBTITLE} —— 与黑名单助手(WBBlackList)相互独立, 可单独运行。</p>

<h3>快捷键(全局, 游戏中也能按)</h3>
<ul>{keys}</ul>
<p>要点:</p>
<ul>
<li>只要<b>按住右Shift 再按小键盘对应数字</b>就会触发, <b>与其它按键是否按住无关</b>
    (例如一直按着 W 前进时照样能触发);</li>
<li>小键盘 NumLock <b>开或关都可以</b>;</li>
<li>游戏需要以“全屏窗口(无边框)”或窗口模式运行, 单用全屏独占也不影响本程序按键监听;</li>
<li>结束录制与标记只在录制中有效(未录制时按了会提示“当前没有在录制”)。</li>
</ul>

<h3>界面怎么用</h3>
<ul>
<li><b>“展开/收起”列</b>: 每行的一条轨迹前面有个<b>眼睛</b>图标 ——
    点亮 = 该轨迹画在地图上, 再点一下 = 收起; 分组行这里是展开箭头。</li><li><b>侧栏是四层</b>: 地图 → 游戏模式 → 版本(战区布局) → 轨迹。
    同一张地图有多个模式、同一模式还可能有多个版本(战区位置不同), 分开归组才好对比。</li>
<li><b>“信息”列</b>: 分组行显示该组有几条轨迹; 轨迹行显示用时;
    只有缓存图片、没录过轨迹的地图显示“仅缓存”。</li>
<li><b>单击选中 / Shift、Ctrl 多选</b>: 选中的那几条就是<b>回放对象</b>;
    选中的轨迹会被高亮成速度配色, 但<b>显示开关始终是眼睛</b> ——
    眼睛没点亮的轨迹不会被画出来(即使它正被选中)。</li>
<li><b>双击某条轨迹</b>: 把它所在的“地图·模式·版本”定为<b>基准</b>,
    同时显示它、并把底图切到它那一张; 基准所在版本行前面会有一个<b>图钉</b>。
    定了基准后, 显示与多选<b>只允许在同一版本内</b>(不同交战区域的线路没法直接比)。</li>
<li><b>右键</b>: 轨迹行可显示/隐藏/删除; 版本行可改名(如把“区域 1”改成“大地图”)、
    整组显示或隐藏; 地图行可重命名。</li>
</ul>

<h3>录制</h3>
<ul>
<li>三个按钮 / 三个快捷键一一对应: 开始 → 标记 → 结束; 结束时该条轨迹立即入库。</li>
<li>“<b>以速度从零变化时刻作为起始时间点</b>”: 勾选后按下开始时<b>不立即计时</b>,
    等你切回游戏、车真正动起来, 以“最近一次速度为 0”的时刻作为起点 ——
    切窗口的几十毫秒不会被算进成绩(每次启动默认不勾选)。</li>
<li>“<b>采样间隔</b>”: 越小越密。8111 陆战数据约每 40ms 更新一次, 40ms 即与之匹配;
    20ms(≈50Hz)已接近请求上限, 右侧会显示实际值。</li>
<li><b>录制期间其余功能全部锁定</b>(侧栏、回放、采样间隔、地图管理), 避免和录制抢界面;
    开始录制时若正在看别的地图/版本, 程序会先切回游戏当前地图。</li>
<li>战局外(8111 只给 “?” 占位图)无法开始录制; 等待移动期间结束 = 取消, 不落盘。</li>
</ul>

<h3>回放</h3>
<ul>
<li>回放对象 = 侧栏选中的轨迹(限同一版本); 没选中时顺次退回“眼睛点亮的” → “刚录制的那条”。</li>
<li>多条同时回放: 统一从 00:00 开始, <b>以最长的那条播完才结束</b>, 每条各有一个光标。</li>
<li>“到下一标记暂停”跨轨迹取<b>当前进度之后最近</b>的标记; 倍速 0.5X ~ 16X, 会记住选择。</li>
<li>回放期间其余功能同样锁定, 点“■ 结束播放”退出。</li>
</ul>

<h3>地图与战区</h3>
<ul>
<li>8111 <b>不提供地图名</b>, 所以用<b>地图图片的内容指纹</b>区分地图, 名字由你在
    「地图 → 地图管理…」里自己填; 进战局时图片会自动缓存到 data/maps/, 同一张图只存一次,
    关掉游戏后也能用缓存底图看回放。</li>
<li><b>战区(A/B/C)</b> 来自 8111 的 capture_zone 对象, 可在地图上画小菱形 + 字母
    (菜单「设置」里开关)。颜色是<b>归属</b>: 蓝 = 我方, 红 = 敌方, 白 = 中立;
    正在被占领时在本阵营色里闪烁。</li>
<li>8111 也不提供模式名, 程序按<b>战区数量</b>判定: 3 个 = 战区控制, 2 个 = 战区攻陷,
    1 个 = 战区争夺。这正是侧栏第二层的来源。</li>
<li>战区坐标串作为“版本指纹”存进每条轨迹, 所以同图不同交战区域会被分开归组;
    见过的战区布局会存进 routes.json, 战局结束后依旧能画出来。</li>
</ul>

<h3>音效</h3>
<ul>
<li>开始 / 结束 / 标记 分别播不同的音效(默认就是 Windows 自带的
    <code>Speech On.wav</code>、<code>Speech Off.wav</code>、<code>Windows Balloon.wav</code>,
    在 <code>%SystemRoot%\\Media</code> 里), 以便在游戏中凭听觉确认;</li>
<li>菜单「<b>音效</b>」里可以: 一键<b>启用/关闭</b>提示音; 打开「音效设置」
    调<b>音量</b>(0~100%)、给四个动作分别<b>换成本地的 .wav 文件</b>(带试听), 或恢复默认;
    设置会记住;</li>
<li>调音量是<b>把音效样本按比例重新采样后播放</b>, <b>不会改动系统音量</b>
    (Windows 的 waveaudio 驱动不支持单独给某个音效设音量);</li>
<li>音量调到 0 等于静音; 自定义文件写错了/被删了会自动退回默认音效。</li>
</ul>

<h3>数据存在哪</h3>
<ul>
<li>轨迹与地图名: <code>data/routes.json</code>(原子写入, 断电不会写坏);</li>
<li>地图图片缓存: <code>data/maps/</code>;</li>
<li>运行日志: <code>data/route_tester.log</code>(快捷键触发、换图、录制起止都会记, 排查问题看它);</li>
<li>目录版(onedir)的数据在 exe 同级 <code>data\\</code>; 源码运行则在项目根目录。</li>
</ul>
"""
